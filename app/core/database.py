# ---------------------------------------------------------------------------
# Database Engine & Session Factory
# ---------------------------------------------------------------------------

engine = create_async_engine(
    settings.DATABASE_URL,
    echo=settings.DEBUG,
    future=True,
)

async_session = async_sessionmaker(
    engine,
    class_=AsyncSession,
    expire_on_commit=False,
)


async def init_db():
    """Create all tables if they do not already exist."""
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)


async def execute_safe_readonly_query(sql_string: str, params: Optional[Dict[str, Any]] = None) -> List[Dict[str, Any]]:
    """Execute a validated read-only SQL query with database-level safeguards."""
    params = params or {}
    async with async_session() as session:
        # SQLite database-level read-only safeguard:
        try:
            await session.execute(text("PRAGMA query_only = ON;"))
            result = await session.execute(text(sql_string), params)
            rows = result.mappings().fetchmany(settings.SQL_MAX_ROWS)
            return [dict(row) for row in rows]
        finally:
            await session.execute(text("PRAGMA query_only = OFF;"))


