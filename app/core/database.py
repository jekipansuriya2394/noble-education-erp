"""Database models, connection engine, and read-only query runner."""

import datetime
from typing import Any, Dict, List, Optional
from sqlalchemy import (
    Column, Integer, String, Float, ForeignKey, DateTime, Text, Boolean, text
)
from sqlalchemy.ext.asyncio import create_async_engine, AsyncSession, async_sessionmaker
from sqlalchemy.orm import declarative_base, relationship as orm_relationship

from app.core.config import settings

Base = declarative_base()

